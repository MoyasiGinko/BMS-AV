"""AI Assistant domain models: AiConversation, AiMessage, and AiAuditLog."""

from __future__ import annotations

from typing import ClassVar

from django.conf import settings
from django.db import models
from django.utils.translation import gettext_lazy as _

from apps.core.models import TenantManager, TenantModel


class MessageRole(models.TextChoices):
    USER = "user", _("User")
    ASSISTANT = "assistant", _("Assistant")
    SYSTEM = "system", _("System")
    TOOL = "tool", _("Tool")


class AuditStatus(models.TextChoices):
    SUCCESS = "success", _("Success")
    ERROR = "error", _("Error")
    PERMISSION_DENIED = "permission_denied", _("Permission Denied")
    QUOTA_EXCEEDED = "quota_exceeded", _("Quota Exceeded")


class AiConversation(TenantModel):
    """Scoped multi-turn chat conversation between a tenant user and the AI assistant."""

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="ai_conversations",
    )
    title = models.CharField(_("title"), max_length=255, default=_("New Conversation"))

    objects: ClassVar[TenantManager] = TenantManager()
    all_tenants: ClassVar[models.Manager[AiConversation]] = models.Manager()

    class Meta(TenantModel.Meta):
        verbose_name = _("AI Conversation")
        verbose_name_plural = _("AI Conversations")
        ordering = ["-updated_at"]
        indexes = [
            models.Index(fields=["organization", "user", "-updated_at"]),
        ]

    def __str__(self) -> str:
        return f"{self.title} ({self.organization})"


class AiMessage(TenantModel):
    """Single message within an AI conversation, supporting tool calls and pending actions."""

    conversation = models.ForeignKey(
        AiConversation,
        on_delete=models.CASCADE,
        related_name="messages",
    )
    role = models.CharField(
        _("role"),
        max_length=20,
        choices=MessageRole.choices,
        default=MessageRole.USER,
    )
    content = models.TextField(_("content"), blank=True, default="")
    tool_calls = models.JSONField(
        _("tool calls"),
        default=list,
        blank=True,
        help_text=_("List of tool calls generated by LLM"),
    )
    tool_results = models.JSONField(
        _("tool results"),
        default=list,
        blank=True,
        help_text=_("Execution results from tool registry handlers"),
    )
    pending_action = models.JSONField(
        _("pending action"),
        default=dict,
        blank=True,
        help_text=_("Draft mutation action awaiting user review and confirmation"),
    )
    is_action_confirmed = models.BooleanField(
        _("action confirmed"),
        default=False,
        help_text=_("Whether the pending action was confirmed and executed"),
    )
    token_usage = models.IntegerField(_("token usage"), default=0)

    objects: ClassVar[TenantManager] = TenantManager()
    all_tenants: ClassVar[models.Manager[AiMessage]] = models.Manager()

    class Meta(TenantModel.Meta):
        verbose_name = _("AI Message")
        verbose_name_plural = _("AI Messages")
        ordering = ["created_at"]
        indexes = [
            models.Index(fields=["organization", "conversation", "created_at"]),
        ]

    def __str__(self) -> str:
        return f"[{self.role}] {self.content[:40]} ({self.conversation_id})"


class AiAuditLog(TenantModel):
    """Immutable audit trail of AI model invocations, token costs, and tool executions."""

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="ai_audit_logs",
    )
    conversation = models.ForeignKey(
        AiConversation,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="audit_logs",
    )
    provider = models.CharField(_("provider"), max_length=64, default="fake")
    model_name = models.CharField(_("model name"), max_length=128, default="default")
    tool_name = models.CharField(_("tool name"), max_length=128, blank=True, default="")
    prompt_tokens = models.IntegerField(_("prompt tokens"), default=0)
    completion_tokens = models.IntegerField(_("completion tokens"), default=0)
    latency_ms = models.IntegerField(_("latency ms"), default=0)
    status = models.CharField(
        _("status"),
        max_length=32,
        choices=AuditStatus.choices,
        default=AuditStatus.SUCCESS,
        db_index=True,
    )
    action_confirmed = models.BooleanField(_("action confirmed"), default=False)
    error_message = models.TextField(_("error message"), blank=True, default="")
    metadata = models.JSONField(_("metadata"), default=dict, blank=True)

    objects: ClassVar[TenantManager] = TenantManager()
    all_tenants: ClassVar[models.Manager[AiAuditLog]] = models.Manager()

    class Meta(TenantModel.Meta):
        verbose_name = _("AI Audit Log")
        verbose_name_plural = _("AI Audit Logs")
        ordering = ["-created_at"]
        indexes = [
            models.Index(fields=["organization", "user", "-created_at"]),
            models.Index(fields=["organization", "status", "-created_at"]),
        ]

    def __str__(self) -> str:
        return f"AuditLog {self.public_id} [{self.status}] {self.provider}/{self.tool_name}"
